// ─── Timestamp helpers ────────────────────────────────────────────────────────

function minsAgo(minutes: number): string {
  return new Date(Date.now() - minutes * 60 * 1000).toISOString();
}

function hoursAgo(hours: number): string {
  return minsAgo(hours * 60);
}

